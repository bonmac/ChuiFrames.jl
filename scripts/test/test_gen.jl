using TOML

"Copy only the generator's sources and outputs into a scratch dir."
function gen_sandbox(root = ROOT)
    d = mktempdir()
    for rel in (".agents", ".claude/agents", ".codex/agents", ".claude/hooks", "CLAUDE.md", "AGENTS.md",
                "risk.toml", ".github/pull_request_template.md", "docs/CHECK_COVERAGE.md")
        src = joinpath(root, rel)
        ispath(src) || continue
        mkpath(dirname(joinpath(d, rel)))
        cp(src, joinpath(d, rel))
    end
    return d
end
quiet_check(d) = capture(() -> Gen.check(d))
"A gen sandbox whose factory.toml requires no read-only roots, whatever the host checkout says (0.2.4)."
function gen_sandbox_noroots(root = ROOT)
    d = gen_sandbox(root)
    rm(joinpath(d, ".agents/factory.local.toml"); force = true)   # machine-local roots (a coordinator has them)
    write(joinpath(d, ".agents/factory.toml"), "version = 1\n[bash_guard]\nread_only_roots = []\nrequire_read_only_roots = false\n")
    return d
end

@testset "gen.jl" begin
    @test first(quiet_check(ROOT))

    @testset "every registry field reaches the generated agent file" begin
        reg = TOML.parsefile(joinpath(ROOT, ".agents/agent-registry.toml"))
        for a in reg["agents"]
            md = read(joinpath(ROOT, ".claude/agents/$(a["name"]).md"), String)
            for (k, v) in a, x in (v isa AbstractVector ? v : [v])
                @test occursin(string(x), md) || (println("field $k of $(a["slug"]) missing"); false)
            end
            @test occursin(Gen.body(ROOT, a), md)
            @test issubset(keys(a), [Gen.REQUIRED; Gen.OPTIONAL])
        end
        # the [lanes] fields reach limits.env
        env = read(joinpath(ROOT, ".claude/hooks/limits.env"), String)
        @test occursin("MAX_OPEN_LANES=$(reg["lanes"]["max_open"])", env)
        @test occursin("LEDGER=$(reg["lanes"]["ledger"])", env)
    end

    @testset "AGENTS.md is CLAUDE.md minus claude-only blocks, plus the roster" begin
        agents = read(joinpath(ROOT, "AGENTS.md"), String)
        @test !occursin("claude-only", agents)
        @test occursin("## Agent roster", agents)
        @test occursin("## Non-negotiables", agents)
    end

    @testset "--check catches drift, orphans, unknown fields, missing bodies" begin
        d = gen_sandbox()
        write(joinpath(d, "AGENTS.md"), "hand edit\n")
        @test !first(quiet_check(d))
        capture(() -> Gen.write_all(d))
        @test first(quiet_check(d))
        write(joinpath(d, ".claude/agents/old-role.md"), "<!-- GENERATED by scripts/gen.jl from x -->\n")
        ok, out = quiet_check(d)
        @test !ok && occursin("orphaned .claude/agents/old-role.md", out)
        capture(() -> Gen.write_all(d))
        @test !isfile(joinpath(d, ".claude/agents/old-role.md"))
        reg = joinpath(d, ".agents/agent-registry.toml")
        txt = read(reg, String)
        write(reg, replace(txt, "slug = \"critic\"" => "slug = \"critic\"\nunused_field = 1"; count = 1))
        @test_throws Gen.GenError Gen.outputs(d)
        write(reg, txt)
        rm(joinpath(d, ".agents/bodies/critic.md"))
        @test_throws Gen.GenError Gen.outputs(d)
    end

    @testset "check register covers every hook and guard script" begin
        checks = Gen.load_checks(ROOT)
        by = Set(c["prevented_by"] for c in checks)
        for f in readdir(HOOKS)
            endswith(f, ".sh") && !startswith(f, "_") || continue   # _*.sh: sourced libraries
            @test ".claude/hooks/$f" in by
        end
        for s in ("gen.jl", "dod.jl", "ratchet.jl", "check_docs.jl", "ci.jl", "lane.jl", "sync_factory.jl",
                  "check_claims.jl", "evidence.jl", "changelog.jl")
            @test "scripts/$s" in by
        end
        for c in checks
            @test isfile(joinpath(ROOT, c["test"]))
            @test isfile(joinpath(ROOT, c["prevented_by"]))
        end
    end

    @testset ".agents/factory.toml read_only_roots -> .claude/hooks/read-only-roots.txt" begin
        d = gen_sandbox()
        cfg = joinpath(d, ".agents/factory.toml")
        write(cfg, "version = 1\n[bash_guard]\nread_only_roots = [\"~/ref/a/\", \"/abs/b\"]\n")
        @test !first(quiet_check(d))                                   # drifted until regenerated
        capture(() -> Gen.write_all(d))
        txt = read(joinpath(d, ".claude/hooks/read-only-roots.txt"), String)
        @test occursin("GENERATED", txt) && occursin("\n~/ref/a\n/abs/b\n", txt)   # trailing / dropped
        for bad in ("[\"rel/path\"]", "[\"~/has space\"]", "[\"~/glob*\"]", "[\"/a/[b]\"]")
            write(cfg, "version = 1\n[bash_guard]\nread_only_roots = $bad\n")
            @test_throws Gen.GenError Gen.outputs(d)
        end
        write(cfg, "version = 1\n[bash_guard]\nreadonly_roots = []\n")  # a typo must not disable the guard
        @test_throws Gen.GenError Gen.outputs(d)
        # 0.2.3: the gitignored factory.local.toml adds roots (merged, deduplicated); only that key
        loc = joinpath(d, ".agents/factory.local.toml")
        write(cfg, "version = 1\n[bash_guard]\nread_only_roots = [\"/abs/b\"]\nrequire_read_only_roots = true\n")
        write(loc, "[bash_guard]\nread_only_roots = [\"~/private/ref\", \"/abs/b\"]\n")
        out = Gen.outputs(d)
        @test occursin("\n/abs/b\n~/private/ref\n", out[".claude/hooks/read-only-roots.txt"])
        @test occursin("READ_ONLY_ROOTS_REQUIRED=1", out[".claude/hooks/limits.env"])
        for bad in ("[bash_guard]\nread_only_roots = [\"rel\"]\n", "[bash_guard]\nrequire_read_only_roots = false\n",
                    "[check_docs]\nexclude = []\n")
            write(loc, bad)
            @test_throws Gen.GenError Gen.outputs(d)
        end
        rm(loc)
        # hermetic (0.2.4): the coordinator's own factory.toml requires roots
        @test occursin("READ_ONLY_ROOTS_REQUIRED=0", Gen.outputs(gen_sandbox_noroots())[".claude/hooks/limits.env"])
        rm(cfg)                                                        # no config: an empty list
        @test count(l -> !startswith(l, "#"), split(Gen.outputs(d)[".claude/hooks/read-only-roots.txt"], '\n'; keepempty = false)) == 0
    end

    @testset "settings.json wires every hook, and only existing ones" begin
        settings = joinpath(ROOT, ".claude/settings.json")
        @test success(pipeline(`jq -e .hooks $settings`; stdout = devnull))
        wired = Set(m.captures[1] for m in eachmatch(r"\.claude/hooks/([a-z_]+\.sh)", read(settings, String)))
        hooks = Set(f for f in readdir(HOOKS) if endswith(f, ".sh") && !startswith(f, "_"))
        @test wired == hooks
    end

    if IN_FACTORY
        @testset "MANIFEST [generated] matches gen.jl outputs" begin
            gen = TOML.parsefile(joinpath(FACTORY, "MANIFEST.toml"))["generated"]["paths"]
            outs = collect(keys(Gen.outputs(ROOT)))
            @test all(o -> any(g -> DoD.globmatch(g, o), gen), outs)
            @test all(g -> any(o -> DoD.globmatch(g, o), outs), gen)
        end
    end
end
