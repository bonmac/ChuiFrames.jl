@testset "sync_factory.jl" begin
    if !IN_FACTORY
        # Not a failure and not a known bug, so no @test_skip (it counts as "Broken"): these tests
        # exercise sync_factory.jl against a scratch copy of the factory, and they run in
        # factory/template, whose copy of the script the vendored one matches byte for byte
        # (its hash is in .factory-version). The coordinator syncs with factory/template's script.
        @info "sync_factory tests run in factory/template (they need factory/MANIFEST.toml); not run in a vendored repo"
    else
        fac = joinpath(mktempdir(), "factory")                    # a scratch copy we can change
        cp(FACTORY, fac)
        # runtime scratch a template-rooted session leaves behind is never offered
        mkpath(joinpath(fac, "template/.lanes")); write(joinpath(fac, "template/.lanes/ledger.jsonl"), "{}\n")
        mkpath(joinpath(fac, "template/.claude")); write(joinpath(fac, "template/.claude/settings.local.json"), "{}\n")
        @test !any(
            p -> startswith(p[2], ".lanes/") || p[2] == ".claude/settings.local.json",
            SyncFactory.plan(fac, mktempdir(), "package", Dict{String, Any}())
        )
        sync(args...; to) = capture(() -> SyncFactory.main(["--from", fac, "--to", to, args...]))
        to = tmp_repo()
        rc, out = sync(; to)
        @test rc == 0 && occursin("dry run", out) && !isfile(joinpath(to, ".factory-version"))
        rc, out = sync("--apply"; to)
        @test rc == 0 || (print(out); false)
        rec = TOML.parsefile(joinpath(to, ".factory-version"))
        @test rec["version"] == strip(read(joinpath(fac, "VERSION"), String)) && rec["profile"] == "package"
        @test isfile(joinpath(to, "CLAUDE.md")) && isfile(joinpath(to, ".github/workflows/CI.yml"))
        @test !haskey(rec["managed"], "CLAUDE.md")               # seeded: repo-owned
        @test isfile(joinpath(to, "AGENTS.md"))                   # generated by gen.jl after sync
        @test first(capture(() -> Gen.check(to)))
        @test Base.Filesystem.filemode(joinpath(to, "scripts/lane")) & 0o100 != 0
        # 0.2.4: the template's executables (every hook, every script; 15280a8 dropped +x from four) stay executable
        exe(p) = Base.Filesystem.filemode(p) & 0o100 != 0
        want = [
            rel for rel in SyncFactory.template_files(joinpath(FACTORY, "template"))
                if occursin(r"^(\.claude/hooks/[^/]+\.sh|scripts/[^/]+\.jl|scripts/lane|scripts/test/runtests\.jl)$", rel)
        ]
        @test length(want) >= 25
        for rel in want
            @test exe(joinpath(FACTORY, "template", rel)) || (println("template file not executable: $rel"); false)
            @test exe(joinpath(to, rel)) || (println("synced file not executable: $rel"); false)
        end
        chmod(joinpath(to, "scripts/lane"), 0o644)                          # a mode-only difference is repaired
        capture(() -> SyncFactory.main(["--from", fac, "--to", to, "--apply"]))
        @test Base.Filesystem.filemode(joinpath(to, "scripts/lane")) & 0o100 != 0
        rc, out = sync(; to)
        @test rc == 0 && !occursin("update", out) && !occursin("add ", out)

        # seeded files are never overwritten
        write(joinpath(to, "CLAUDE.md"), read(joinpath(to, "CLAUDE.md"), String) * "local\n")
        write(joinpath(fac, "template/CLAUDE.md"), read(joinpath(fac, "template/CLAUDE.md"), String) * "upstream\n")
        rc, out = sync("--apply"; to)
        @test rc == 0 && occursin("seeded-differs", out) && occursin("local", read(joinpath(to, "CLAUDE.md"), String))

        # a factory update to an unedited managed file is applied
        f = "template/.claude/commands/lanes.md"
        write(joinpath(fac, f), read(joinpath(fac, f), String) * "\nUpstream addition.\n")
        rc, out = sync("--apply"; to)
        @test rc == 0 && occursin("Upstream addition", read(joinpath(to, ".claude/commands/lanes.md"), String))

        # a local edit to a managed file the factory did not change is kept, and does not block
        write(joinpath(to, ".claude/commands/intake.md"), "# my intake\n")
        rc, out = sync("--apply"; to)
        @test rc == 0 && occursin("local-modified", out)
        @test read(joinpath(to, ".claude/commands/intake.md"), String) == "# my intake\n"
        rc, out = sync(; to)
        @test rc == 0 && occursin("local-modified", out)           # still recognised after a re-sync

        # a local edit to a managed file the factory also changed is a conflict: shown, not overwritten without --force
        write(joinpath(to, ".claude/hooks/precompact.sh"), "# local edit\n")
        write(
            joinpath(fac, "template/.claude/hooks/precompact.sh"),
            read(joinpath(fac, "template/.claude/hooks/precompact.sh"), String) * "# upstream\n"
        )
        rc, out = sync("--apply"; to)
        @test rc == 1 && occursin("conflict", out)
        @test read(joinpath(to, ".claude/hooks/precompact.sh"), String) == "# local edit\n"
        rc, out = sync("--apply", "--force"; to)
        @test rc == 0 && occursin("# upstream", read(joinpath(to, ".claude/hooks/precompact.sh"), String))

        # a dropped file is reported, never deleted
        rm(joinpath(fac, "template/.claude/commands/lanes.md"))
        rc, out = sync(; to)
        @test occursin("removed-upstream", out) && isfile(joinpath(to, ".claude/commands/lanes.md"))

        # a managed file the factory now seeds is reported as now-seeded, not removed-upstream,
        # and leaves the managed record (0.2.0 reported it as removed-upstream)
        tc = ".claude/commands/test-changed.md"
        m = read(joinpath(fac, "MANIFEST.toml"), String)
        write(joinpath(fac, "MANIFEST.toml"), replace(m, "paths = [\n  \"CLAUDE.md\"," => "paths = [\n  \"$tc\",\n  \"CLAUDE.md\","; count = 1))
        rc, out = sync(; to)
        @test rc == 0 && occursin(r"now-seeded\s+\.claude/commands/test-changed\.md", out) &&
            !occursin(r"removed-upstream\s+\.claude/commands/test-changed\.md", out)
        rc, out = sync("--apply"; to)
        @test rc == 0 && !haskey(TOML.parsefile(joinpath(to, ".factory-version"))["managed"], tc) && isfile(joinpath(to, tc))
        rc, out = sync(; to)
        @test !occursin("test-changed", out)                      # now repo-owned and unchanged: nothing to say
        write(joinpath(fac, "MANIFEST.toml"), m)

        @test rec["adr_dir"] == "docs/adr"
        @test isempty(CheckDocs.config_list(CheckDocs.factory_config(to), "bash_guard", "read_only_roots"))
        # 0.2.2: the package overlay excludes the verbatim copies every package carries
        pcfg = CheckDocs.factory_config(to)
        @test CheckDocs.config_list(pcfg, "check_docs", "exclude") == ["docs/agent/*", "test/contracts/*.md"]
        @test !haskey(rec["managed"], ".agents/factory.toml")                   # seeded: repo-owned
        mkpath(joinpath(to, "docs/agent")); write(joinpath(to, "docs/agent/ECOSYSTEM.md"), "See `contracts/README.md`.\n")
        write(joinpath(to, "test/contracts/chui-core.md"), "See `adr/0010-cross-repo-workflow.md`.\n")
        rc, out = capture(() -> CheckDocs.main(["--root", to, "--external", "docs/agent/*"]))   # CLAUDE.md names them; the lead copies them in
        @test rc == 0 || (print(out); false)
        rm(joinpath(to, "docs/agent"); recursive = true); rm(joinpath(to, "test/contracts/chui-core.md"))
        @test isfile(joinpath(to, "test/contracts/Project.toml")) && isfile(joinpath(to, "test/contracts/runtests.jl"))
        lic = read(joinpath(to, "LICENSE"), String)                                # 0.2.3: seeded MIT, to fill in
        @test startswith(lic, "MIT License") && occursin("<YEAR> <COPYRIGHT HOLDER>", lic) && !haskey(rec["managed"], "LICENSE")

        # the coordinator profile skips package-only files, takes its overlay, and keeps ADRs in adr/
        c = tmp_repo()
        rc, out = sync("--apply", "--profile", "coordinator"; to = c)
        @test rc == 0 && !isfile(joinpath(c, ".github/workflows/CI.yml")) && isfile(joinpath(c, ".github/workflows/Guards.yml"))
        @test !isdir(joinpath(c, "test"))
        crec = TOML.parsefile(joinpath(c, ".factory-version"))
        @test crec["adr_dir"] == "adr" && DoD.adr_dir(c) == "adr"
        @test !isdir(joinpath(c, "docs/adr")) && !isdir(joinpath(c, "adr"))      # adr/ is the coordinator's own
        cfg = CheckDocs.factory_config(c)                                          # overlay, seeded
        # 0.2.3: no committed roots (they are private); they come from the gitignored factory.local.toml
        @test isempty(CheckDocs.config_list(cfg, "bash_guard", "read_only_roots")) && cfg["bash_guard"]["require_read_only_roots"]
        @test !haskey(crec["managed"], ".agents/factory.toml")                     # seeded: repo-owned
        @test occursin("READ_ONLY_ROOTS_REQUIRED=1", read(joinpath(c, ".claude/hooks/limits.env"), String))
        roots = read(joinpath(c, ".claude/hooks/read-only-roots.txt"), String)     # rendered by gen.jl after sync
        @test all(l -> startswith(l, "#"), split(roots, '\n'; keepempty = false))
        guard(cmd) = run(
            pipeline(
                ignorestatus(addenv(`sh $(joinpath(c, ".claude/hooks/bash_guard.sh"))`, "CLAUDE_PROJECT_DIR" => c));
                stdin = IOBuffer(bash(cmd)), stdout = devnull, stderr = devnull
            )
        ).exitcode
        @test guard("ls") == 2 && guard("julia scripts/gen.jl") == 0                 # required, none: fails closed
        write(joinpath(c, ".agents/factory.local.toml"), "[bash_guard]\nread_only_roots = [\"~/ro-fixture/ref-a/\"]\n")
        capture(() -> Gen.write_all(c))
        @test occursin("\n~/ro-fixture/ref-a\n", read(joinpath(c, ".claude/hooks/read-only-roots.txt"), String))
        @test guard("ls") == 0 && guard("cd ~/ro-fixture/ref-a && uv sync") == 2
        for f in (".agents/factory.local.toml", ".claude/hooks/read-only-roots.txt")   # never committed
            @test success(pipeline(`git -C $c check-ignore -q --no-index $f`))
        end
        rm(joinpath(c, ".claude/hooks/read-only-roots.txt"))
        @test guard("ls") == 2                                                     # the rendered file missing
        @test first(capture(() -> Gen.check(c)))                                   # gitignored: --check skips it
        capture(() -> Gen.write_all(c))
        rm(joinpath(c, ".agents/factory.local.toml"))
        @test occursin("`adr/0000-template.md`", read(joinpath(c, ".agents/bodies/architect.md"), String))
        @test !occursin("docs/adr/", read(joinpath(c, "CLAUDE.md"), String))      # seeded text rewritten
        @test !occursin("docs/adr/", read(joinpath(c, ".claude/commands/intake.md"), String))
        @test occursin("docs/adr", read(joinpath(c, "scripts/dod.jl"), String))   # code is never rewritten
        rc, out = sync("--profile", "coordinator"; to = c)                         # rendered files compare equal
        @test rc == 0 && !occursin("update", out) && !occursin("conflict", out) && !occursin("add ", out)
        # the ADR files themselves move when a profile keeps them
        open(joinpath(fac, "MANIFEST.toml"), "a") do io
            println(io, "\n[profiles.custom]\nadr_dir = \"decisions\"\nexclude = [\".github/workflows/*\", \"test/*\"]")
        end
        k = tmp_repo()
        rc, out = sync("--apply", "--profile", "custom"; to = k)
        @test rc == 0 && isfile(joinpath(k, "decisions/0000-template.md")) && isfile(joinpath(k, "decisions/README.md"))
        @test !isdir(joinpath(k, "docs/adr")) && TOML.parsefile(joinpath(k, ".factory-version"))["adr_dir"] == "decisions"
        @test haskey(TOML.parsefile(joinpath(k, ".factory-version"))["managed"], "decisions/0000-template.md")
        # a bad profile key is an error, not ignored
        open(joinpath(fac, "MANIFEST.toml"), "a") do io
            println(io, "\n[profiles.typo]\nexlude = []")
        end
        @test_throws ErrorException SyncFactory.plan(fac, k, "typo", Dict{String, Any}())
    end
end
