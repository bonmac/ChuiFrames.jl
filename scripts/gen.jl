#!/usr/bin/env julia
# gen.jl: write every derived factory file from its single source.
#
#   julia scripts/gen.jl [--root DIR]     write the files
#   julia scripts/gen.jl --check          exit 1 if any file is missing, drifted or orphaned
#
# Sources -> outputs:
#   .agents/agent-registry.toml + .agents/bodies/*.md -> .claude/agents/*.md, .codex/agents/*.toml,
#                                                        .claude/hooks/limits.env
#   CLAUDE.md (+ registry roster)                     -> AGENTS.md
#   risk.toml                                         -> .claude/hooks/protected-paths.txt,
#                                                        .github/pull_request_template.md
#   .agents/checks.toml (+ checks.local.toml)         -> docs/CHECK_COVERAGE.md
#   .agents/factory.toml [bash_guard]                 -> .claude/hooks/limits.env, .claude/hooks/read-only-roots.txt
#     + .agents/factory.local.toml (gitignored)          (the roots file is gitignored too)
# Stdlib only (TOML), so it runs before any environment is instantiated.
module Gen

    using TOML
    include(joinpath(@__DIR__, "_common.jl"))

    const BANNER = "GENERATED by scripts/gen.jl from %SRC% - DO NOT EDIT BY HAND."
    banner_md(src) = "<!-- " * replace(BANNER, "%SRC%" => src) * " -->"
    banner_hash(src) = "# " * replace(BANNER, "%SRC%" => src)

    # Every agent field the generator reads. An unknown field is an error, and
    # scripts/test/test_gen.jl asserts each of these values reaches the output.
    const REQUIRED = [
        "slug", "name", "role", "description", "model", "color", "default_mode",
        "file_scope", "scorecard", "output_format",
    ]
    const OPTIONAL = ["tools", "disallowed_tools"]
    const MODELS = ("opus", "sonnet", "haiku", "fable", "inherit")
    const MODES = ("read_only", "write")
    const TOP_KEYS = ("version", "lanes", "agents")
    const LANE_KEYS = ("max_open", "ledger")
    const TIERS = ("T0", "T1", "T2", "T3")
    const REQUIREMENTS = ("ci", "ref", "spec", "tests", "changelog", "review", "adr")
    const CHECK_KEYS = ("id", "rule", "prevented_by", "runs_in", "test", "blind_spots")

    struct GenError <: Exception
        msg::String
    end
    Base.showerror(io::IO, e::GenError) = print(io, "gen.jl: ", e.msg)
    fail(msg) = throw(GenError(msg))

    readtoml(root, rel) = (p = joinpath(root, rel); isfile(p) ? TOML.parsefile(p) : fail("missing $rel"))

    function load_registry(root)
        reg = readtoml(root, ".agents/agent-registry.toml")
        for k in keys(reg)
            k in TOP_KEYS || fail("registry: unknown top-level key `$k`")
        end
        get(reg, "version", 0) == 1 || fail("registry: version must be 1")
        lanes = get(reg, "lanes", Dict{String, Any}())
        for k in keys(lanes)
            k in LANE_KEYS || fail("registry: unknown [lanes] key `$k`")
        end
        mo = get(lanes, "max_open", 4)
        (mo isa Integer && mo >= 1) || fail("registry: [lanes] max_open must be an integer >= 1")
        agents = get(reg, "agents", Any[])
        isempty(agents) && fail("registry: no [[agents]]")
        seen = Set{String}()
        for a in agents
            for k in keys(a)
                (k in REQUIRED || k in OPTIONAL) || fail("registry: agent `$(get(a, "slug", "?"))` has unknown field `$k`")
            end
            for k in REQUIRED
                haskey(a, k) || fail("registry: agent `$(get(a, "slug", "?"))` lacks `$k`")
            end
            s, n = a["slug"], a["name"]
            occursin(r"^[a-z][a-z0-9_]*$", s) || fail("registry: bad slug `$s`")
            occursin(r"^[a-z][a-z0-9-]*$", n) || fail("registry: bad name `$n`")
            (s in seen || n in seen) && fail("registry: duplicate `$s`/`$n`")
            push!(seen, s, n)
            a["model"] in MODELS || fail("registry: `$s` model must be one of $(MODELS)")
            a["default_mode"] in MODES || fail("registry: `$s` default_mode must be one of $(MODES)")
            isempty(a["scorecard"]) && fail("registry: `$s` has an empty scorecard")
            if a["default_mode"] == "read_only" && !isempty(a["file_scope"])
                fail("registry: read_only agent `$s` must have an empty file_scope")
            end
            isfile(joinpath(root, ".agents/bodies/$s.md")) || fail("registry: missing body .agents/bodies/$s.md")
        end
        return reg
    end

    yq(s) = "\"" * replace(s, "\\" => "\\\\", "\"" => "\\\"") * "\""
    body(root, a) = rstrip(read(joinpath(root, ".agents/bodies/$(a["slug"]).md"), String))
    scope_text(a) = isempty(a["file_scope"]) ? "none (read-only)" : join(("`$g`" for g in a["file_scope"]), ", ")

    function instructions(root, a)
        io = IOBuffer()
        println(io, "## Role\n\n", a["role"], "\n")
        println(io, "Mode: `", a["default_mode"], "`. File scope: ", scope_text(a), ".\n")
        println(io, body(root, a), "\n")
        println(io, "## Output format\n\nReport these sections, in order: ", a["output_format"], ".\n")
        println(io, "## Scorecard\n")
        foreach(x -> println(io, "- ", x), a["scorecard"])
        return String(take!(io))
    end

    function claude_agent(root, a)
        io = IOBuffer()
        println(io, "---")
        println(io, "name: ", a["name"])
        println(io, "description: ", yq(a["description"]))
        println(io, "model: ", a["model"])
        haskey(a, "tools") && println(io, "tools: ", join(a["tools"], ", "))
        haskey(a, "disallowed_tools") && println(io, "disallowedTools: ", join(a["disallowed_tools"], ", "))
        println(io, "color: ", a["color"])
        println(io, "---")
        println(io, banner_md(".agents/agent-registry.toml and .agents/bodies/$(a["slug"]).md"), "\n")
        print(io, instructions(root, a))
        return String(take!(io))
    end

    function codex_agent(root, a)
        io = IOBuffer()
        println(io, banner_hash(".agents/agent-registry.toml"))
        TOML.print(
            io, Dict(
                "name" => a["slug"], "description" => a["description"],
                "developer_instructions" => instructions(root, a)
            ); sorted = true
        )
        return String(take!(io))
    end

    # AGENTS.md = CLAUDE.md minus <!-- claude-only:begin -->...<!-- claude-only:end --> blocks,
    # plus the roster. Wholly generated: no hand-written gaps to go stale.
    function agents_md(root, reg)
        src = read(joinpath(root, "CLAUDE.md"), String)
        occursin("<!-- claude-only:begin -->", src) == occursin("<!-- claude-only:end -->", src) ||
            fail("CLAUDE.md: unbalanced claude-only markers")
        stripped = replace(src, r"<!-- claude-only:begin -->.*?<!-- claude-only:end -->\n?"s => "")
        io = IOBuffer()
        println(io, banner_md("CLAUDE.md and .agents/agent-registry.toml"), "\n")
        println(io, rstrip(stripped), "\n")
        println(io, "## Agent roster\n")
        println(io, "| Agent | Mode | Model | Role |\n|---|---|---|---|")
        for a in reg["agents"]
            println(io, "| `", a["name"], "` | ", a["default_mode"], " | ", a["model"], " | ", a["role"], " |")
        end
        return String(take!(io))
    end

    function limits_env(reg, cfg = Dict{String, Any}())
        lanes = get(reg, "lanes", Dict{String, Any}())
        req = get(get(cfg, "bash_guard", Dict{String, Any}()), "require_read_only_roots", false)
        return banner_hash(".agents/agent-registry.toml [lanes] + .agents/factory.toml [bash_guard]") * "\n" *
            "MAX_OPEN_LANES=$(get(lanes, "max_open", 4))\n" *
            "LEDGER=$(get(lanes, "ledger", ".lanes/ledger.jsonl"))\n" *
            "READ_ONLY_ROOTS_REQUIRED=$(req ? 1 : 0)\n"
    end

    function load_risk(root)
        risk = readtoml(root, "risk.toml")
        get(risk, "default_tier", "") in TIERS || fail("risk.toml: default_tier must be one of $(TIERS)")
        tiers = get(risk, "tiers", Dict{String, Any}())
        Set(keys(tiers)) == Set(TIERS) || fail("risk.toml: [tiers] must define exactly $(TIERS)")
        for (t, d) in tiers
            haskey(d, "summary") || fail("risk.toml: tier $t lacks summary")
            for r in get(d, "requires", String[])
                r in REQUIREMENTS || fail("risk.toml: tier $t requires unknown `$r` (known: $(REQUIREMENTS))")
            end
        end
        for p in get(risk, "protected", Any[])
            get(p, "tier", "") in TIERS || fail("risk.toml: [[protected]] tier must be one of $(TIERS)")
            for g in p["globs"]
                occursin(r"\s", g) && fail("risk.toml: glob `$g` contains whitespace")
            end
        end
        return risk
    end

    function protected_txt(risk)
        io = IOBuffer()
        println(io, banner_hash("risk.toml"))
        println(io, "# <tier> <glob>   (`*` matches across `/`, like sh `case`)")
        for p in get(risk, "protected", Any[]), g in p["globs"]
            println(io, p["tier"], " ", g)
        end
        return String(take!(io))
    end

    function pr_template(risk)
        io = IOBuffer()
        println(io, banner_md("risk.toml"), "\n")
        println(io, "## What and why\n\n<!-- One paragraph. Link the spec or plan (docs/superpowers/...), or label the PR T0. -->\n")
        println(io, "## Risk tier (label the PR with exactly one)\n")
        for t in TIERS
            d = risk["tiers"][t]
            println(io, "- [ ] **", t, "**: ", d["summary"], " Requires: ", join(get(d, "requires", String[]), ", "), ".")
        end
        println(io, "\nProtected paths raise the tier automatically (`scripts/dod.jl`):\n")
        for p in get(risk, "protected", Any[])
            println(io, "- ", p["tier"], ": ", join(("`$g`" for g in p["globs"]), ", "))
        end
        println(io, "\n## Evidence\n\n<!-- Paste the commands you ran and their output. List checks NOT run, and why. -->\n")
        println(io, "## Definition of done\n\n- [ ] `julia scripts/dod.jl` passes\n- [ ] CHANGELOG entry under `## Unreleased`\n- [ ] Reviewer's final report linked")
        return String(take!(io))
    end

    function load_checks(root)
        checks = Any[]
        for rel in (".agents/checks.toml", ".agents/checks.local.toml")
            isfile(joinpath(root, rel)) || continue
            for c in get(TOML.parsefile(joinpath(root, rel)), "checks", Any[])
                for k in keys(c)
                    k in CHECK_KEYS || fail("$rel: check `$(get(c, "id", "?"))` has unknown field `$k`")
                end
                for k in CHECK_KEYS
                    haskey(c, k) || fail("$rel: check `$(get(c, "id", "?"))` lacks `$k`")
                end
                isempty(c["blind_spots"]) && fail("$rel: check `$(c["id"])` declares no blind spots")
                push!(checks, c)
            end
        end
        isempty(checks) && fail("no checks in .agents/checks.toml")
        return checks
    end

    cell(s) = replace(s, "|" => "\\|")
    function check_coverage(checks)
        io = IOBuffer()
        println(io, banner_md(".agents/checks.toml"), "\n")
        println(io, "# Check coverage: what each guard prevents, and what it is blind to\n")
        println(io, "Each rule is \"prevented by\" a named check. A blind spot is a way the rule can be broken")
        println(io, "without that check noticing; reviewers cover blind spots by hand. Edit `.agents/checks.toml`")
        println(io, "(factory-managed) or `.agents/checks.local.toml` (repo-owned), then run `julia scripts/gen.jl`.\n")
        println(io, "| Rule | Prevented by | Runs in | Test | Blind spots |\n|---|---|---|---|---|")
        for c in checks
            println(
                io, "| ", cell(c["rule"]), " | `", c["prevented_by"], "` | ", join(c["runs_in"], ", "),
                " | `", c["test"], "` | ", cell(join(c["blind_spots"], "; ")), " |"
            )
        end
        return String(take!(io))
    end

    # One root per line for bash_guard.sh (which expands a leading ~). Inside a root only
    # read-only commands may run. The list is repo-owned in .agents/factory.toml plus the
    # machine-local, gitignored .agents/factory.local.toml (private paths are never committed);
    # the output is gitignored too, and bash_guard.sh fails closed without it when
    # `require_read_only_roots = true`.
    function read_only_roots_txt(root)
        cfgs = try
            [(FACTORY_CONFIG, factory_config(root)), (FACTORY_LOCAL, factory_local(root))]
        catch e
            fail(e isa ErrorException ? e.msg : sprint(showerror, e))
        end
        io = IOBuffer()
        println(io, banner_hash("$FACTORY_CONFIG + $FACTORY_LOCAL [bash_guard] read_only_roots"))
        println(io, "# One directory per line; bash_guard.sh allows only read-only commands inside it.")
        println(io, "# Gitignored: it may name private paths. Regenerate with `julia scripts/gen.jl`.")
        seen = Set{String}()
        for (src, cfg) in cfgs, r in config_list(cfg, "bash_guard", "read_only_roots")
            r = rstrip(r, '/')
            (startswith(r, "/") || startswith(r, "~/")) || fail("$src: read_only_roots entry `$r` must be absolute or start with ~/")
            occursin(r"[\s*?\[\]]", r) && fail("$src: read_only_roots entry `$r` contains whitespace or a glob character")
            r in seen || println(io, r)
            push!(seen, r)
        end
        return String(take!(io))
    end

    "Generated files that are gitignored (machine-local): `--check` skips them when absent."
    const LOCAL_OUTPUTS = (".claude/hooks/read-only-roots.txt",)

    "Return Dict(relative path => expected content) for every generated file."
    function outputs(root)
        reg = load_registry(root)
        risk = load_risk(root)
        out = Dict{String, String}()
        for a in reg["agents"]
            out[".claude/agents/$(a["name"]).md"] = claude_agent(root, a)
            out[".codex/agents/$(a["slug"]).toml"] = codex_agent(root, a)
        end
        out["AGENTS.md"] = agents_md(root, reg)
        cfg = try
            factory_config(root)
        catch e
            fail(e isa ErrorException ? e.msg : sprint(showerror, e))
        end
        out[".claude/hooks/limits.env"] = limits_env(reg, cfg)
        out[".claude/hooks/protected-paths.txt"] = protected_txt(risk)
        out[".claude/hooks/read-only-roots.txt"] = read_only_roots_txt(root)
        out[".github/pull_request_template.md"] = pr_template(risk)
        out["docs/CHECK_COVERAGE.md"] = check_coverage(load_checks(root))
        return out
    end

    "Generated files on disk in the agent directories that gen.jl no longer produces."
    function orphans(root, out)
        found = String[]
        for dir in (".claude/agents", ".codex/agents")
            d = joinpath(root, dir)
            isdir(d) || continue
            for f in readdir(d)
                rel = "$dir/$f"
                haskey(out, rel) && continue
                occursin("GENERATED by scripts/gen.jl", read(joinpath(d, f), String)) && push!(found, rel)
            end
        end
        return found
    end

    function check(root; io = stdout)
        out = outputs(root)
        problems = String[]
        for (rel, want) in sort!(collect(out))
            p = joinpath(root, rel)
            if !isfile(p) && rel in LOCAL_OUTPUTS
                continue                                  # gitignored; bash_guard.sh fails closed if it is required
            elseif !isfile(p)
                push!(problems, "missing  $rel")
            elseif read(p, String) != want
                push!(problems, "drifted  $rel")
            end
        end
        append!(problems, "orphaned " .* orphans(root, out))
        foreach(p -> println(io, p), problems)
        println(
            io, isempty(problems) ? "gen.jl --check: OK ($(length(out)) files)" :
                "gen.jl --check: FAILED ($(length(problems)) problems). Run `julia scripts/gen.jl`."
        )
        return isempty(problems)
    end

    function write_all(root; io = stdout)
        out = outputs(root)
        for (rel, content) in out
            p = joinpath(root, rel)
            mkpath(dirname(p))
            (isfile(p) && read(p, String) == content) || write(p, content)
        end
        for rel in orphans(root, out)
            rm(joinpath(root, rel))
            println(io, "removed orphan $rel")
        end
        println(io, "gen.jl: wrote $(length(out)) files")
        return true
    end

    function main(args)
        root = normpath(joinpath(@__DIR__, ".."))
        checkmode = false
        i = 1
        while i <= length(args)
            a = args[i]
            if a == "--check"
                checkmode = true
            elseif a == "--root" && i < length(args)
                root = abspath(args[i += 1])
            else
                println(stderr, "usage: julia scripts/gen.jl [--check] [--root DIR]")
                return 2
            end
            i += 1
        end
        try
            return (checkmode ? check(root) : write_all(root)) ? 0 : 1
        catch e
            e isa GenError || rethrow()
            println(stderr, sprint(showerror, e))
            return 1
        end
    end

end # module

abspath(PROGRAM_FILE) == @__FILE__() && exit(Gen.main(ARGS))
